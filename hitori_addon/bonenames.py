VRC_MMD_BONES_SET: frozenset[str] = frozenset(VRC_MMD_BONES)

_BONE_NAME_SEPARATORS: re.Pattern[str] = re.compile(r"[\s._\-]")


def normalize_bone_name(name: str) -> str:
    """骨骼名归一化: 只留小写字母与数字

    同一个人形骨在不同导入链里的写法不一样 (`Upper_leg.L` / `Upper_Leg.L` / `Upper Leg.L` / `upper_leg_L`),
    只做精确匹配会漏掉一部分顶点, 所以按归一化后的名字比对。
    """
    return "".join(char for char in name.lower() if char.isalnum() and char.isascii())


def _is_lossy_normalized(name: str) -> bool:
    """归一化把名字里的字符去掉了 (日文骨名 `左腕` -> `""`, `腕.L` -> `"l"`, `上半身1` -> `"1"`)

    这种退化键会把任意纯 CJK 名 / `.L` `.R` 结尾的骨骼都判成人形骨 (集合里本来就有 `上半身1`
    这类条目), 所以它们不参与归一化比对。
    """
    keep_all = "".join(char for char in name.lower() if char.isalnum())
    return normalize_bone_name(name) != keep_all


# 只收录归一化没丢字符的条目: 退化键 (`""` / `"1"` / `"2"` / `"l"` / `"r"`) 全部排除
VRC_MMD_NORMALIZED_BONES_SET: frozenset[str] = frozenset(
    normalize_bone_name(name) for name in VRC_MMD_BONES_SET if not _is_lossy_normalized(name)
)

# 带日文的骨名归一化会丢字, 改成按原文 (小写) 比对
# PMX 原文把左右写成前缀 (`左腕`), Blender 导入后是后缀 (`腕.L`), 两种写法都要认
SIDE_PREFIXES: dict[str, str] = {"L": "左", "R": "右"}


def _side_prefix_aliases(name: str) -> list[str]:
    """`腕.L` -> `左腕`; 不是左右后缀的返回空表"""
    aliases = []
    for suffix in (".L", "_L", "-L", ".R", "_R", "-R"):
        if name.endswith(suffix):
            prefix = SIDE_PREFIXES[suffix[1]]
            aliases.append((prefix + name[: -len(suffix)]).lower())
            break
    return aliases


VRC_MMD_LOWERCASE_BONES_SET: frozenset[str] = frozenset(
    [name.lower() for name in VRC_MMD_BONES_SET]
    + [alias for name in VRC_MMD_BONES_SET for alias in _side_prefix_aliases(name)]
)


def _join_bone_name(name: str) -> str:
    """去掉分隔符与大小写差异 (保留日文): `胸１.L` / `胸１_L` / `胸1 L` 归一成同一个"""
    return _BONE_NAME_SEPARATORS.sub("", name.lower())


# 分隔符写法不同但名字相同的条目: `胸１.L` 与 `胸１_L`
VRC_MMD_JOINED_BONES_SET: frozenset[str] = frozenset(
    _join_bone_name(name) for name in VRC_MMD_BONES_SET
)


def is_humanoid_bone_name(name: str) -> bool:
    """是否 VRC / MMD 命名的标准人形骨

    三级比对: 原文小写 (日文骨名与 PMX 的 `左腕` 前缀写法) -> 去分隔符 -> 归一化
    (`Upper_leg.L` / `Upper_Leg.L` / `Upper Leg.L` 全算同一个)。
    """
    lowered = name.lower()
    if lowered in VRC_MMD_LOWERCASE_BONES_SET:
        return True
    if _join_bone_name(name) in VRC_MMD_JOINED_BONES_SET:
        return True
    return normalize_bone_name(name) in VRC_MMD_NORMALIZED_BONES_SET
